// Synthetic receipt definitions for the OCR eval. Each receipt is described
// once here; totals, VAT and the expected extraction are COMPUTED from the
// lines, so the ground truth can't drift from what the image shows.
//
// Prices are VAT-inclusive (as printed in Sweden, France and the UK), except
// `taxAddedOnTop` receipts (US sales tax), where tax is added to the subtotal.

const r2 = (n) => Math.round(n * 100) / 100;

/** VAT contained in a VAT-inclusive amount. */
export const vatOf = (gross, rate) => r2((gross * rate) / (100 + rate));

const line = (label, total, vat, qty = null, unit = null) => ({ label, qty, unit, total, vat });
const each = (label, qty, unit, vat) => line(label, r2(qty * unit), vat, qty, unit);

