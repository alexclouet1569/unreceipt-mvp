/** Everything a correct extraction must contain, derived from the lines. */
export function expectedFor(r) {
  if (r.items.length === 0) {
    const total = r.terminalTotal;
    return {
      merchant_aliases: r.aliases,
      amount: total,
      currency: r.currency,
      receipt_date: r.date,
      tax_amount: r.terminalVat ? vatOf(total, r.terminalVat.rate) : null,
      tax_rate: r.terminalVat ? r.terminalVat.rate : null,
      items_count: 0,
      category: r.category,
    };
  }
  const lines = [...r.items, ...(r.discounts ?? [])];
  const goods = r2(lines.reduce((s, l) => s + (l.total ?? l.amount), 0));
  let total;
  let tax;
  let rates;
  if (r.taxAddedOnTop) {
    tax = r2((goods * r.taxAddedOnTop) / 100);
    total = r2(goods + tax + (r.tip ?? 0));
    rates = [r.taxAddedOnTop];
  } else {
    const byRate = vatTable(r);
    tax = r2(byRate.reduce((s, b) => s + b.vat, 0));
    rates = byRate.map((b) => b.rate);
    total = r2(goods + (r.tip ?? 0));
    // Swedish cash payments round to whole kronor (öresavrundning).
    if (r.cashRounding) total = Math.round(total);
  }
  return {
    merchant_aliases: r.aliases,
    amount: total,
    currency: r.currency,
    receipt_date: r.date,
    tax_amount: tax,
    // A single rate when the receipt has one; null when it mixes rates.
    tax_rate: new Set(rates).size === 1 ? rates[0] : null,
    items_count: r.items.length,
    category: r.category,
  };
}

/** VAT per rate for a VAT-inclusive receipt: [{rate, gross, vat, net}]. */
export function vatTable(r) {
  const lines = [...r.items, ...(r.discounts ?? [])];
  const groups = new Map();
  for (const l of lines) {
    const amount = l.total ?? l.amount;
    groups.set(l.vat, r2((groups.get(l.vat) ?? 0) + amount));
  }
  return [...groups.entries()]
    .sort((a, b) => b[0] - a[0])
    .map(([rate, gross]) => {
      const vat = vatOf(gross, rate);
      return { rate, gross, vat, net: r2(gross - vat) };
    });
}
